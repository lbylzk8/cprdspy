# 画板/画布（与圈点圆兼容）
def 画板(长=8, 宽=8, 坐标等轴=是, 显示坐标轴=否, 背景颜色='#fff'):
    """创建绘图画板。返回 (fig, ax) 元组。"""
    fig, ax = plt.subplots(figsize=(长, 宽))
    if 坐标等轴:
        ax.set_aspect("equal")
    if 显示坐标轴 == 否:
        plt.axis("off")
    fig.patch.set_facecolor(背景颜色)
    return fig, ax


def 画布(长=8, 宽=8, 坐标等轴=是, 显示坐标轴=否, 背景颜色='#fff'):
    """创建绘图画布。返回 (fig, ax) 元组。"""
    fig, ax = plt.subplots(figsize=(长, 宽))
    if 坐标等轴:
        ax.set_aspect("equal")
    if 显示坐标轴 == 否:
        plt.axis("off")
    fig.patch.set_facecolor(背景颜色)
    return fig, ax


