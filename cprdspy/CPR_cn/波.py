from .圆 import 同心圆, 同心圆_填充


def 波_等差(
    振幅=1,
    频率=3,
    相位=12,
    旋转=0,
    使用角度制=True,
    方向='双向',
    颜色='#0f0',
    透明度=1,
    主半径=1,
    圆心=(0, 0),
    点数=1000,
    线型='-',
    线宽=1,
    ax=None,
    显示圆心=True,
    **kwargs,
):
    """等差波形——在圆上分布同心圆，同心圆半径按等差序列排列。

    参数:
        振幅 (float): 同心圆的公差d。
        频率 (int): 每侧同心圆数量。
        相位 (int): 圆心分布点数P。
        旋转 (float): 旋转角度。
        使用角度制 (bool): 旋转是否使用角度制。
        方向 (str): '双向'|'向外'|'向内'。
        主半径 (float): 同心圆基准半径。
    """
    旋转弧度 = np.deg2rad(旋转) if 使用角度制 else 旋转
    for i in range(相位 + 1):
        同心圆(
            圆心=(
                圆心[0] + np.cos(i * 2 * np.pi / 相位 + np.pi / 2 + 旋转弧度),
                圆心[1] + np.sin(i * 2 * np.pi / 相位 + np.pi / 2 + 旋转弧度),
            ),
            n=频率,
            半径=主半径,
            参数=振幅,
            模式='等差',
            方向=方向,
            颜色=颜色,
            透明度=透明度,
            点数=点数,
            线型=线型,
            线宽=线宽,
            ax=ax,
            显示圆心=显示圆心,
            **kwargs,
        )


