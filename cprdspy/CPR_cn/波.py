def 波_波(
    振幅=1,
    频率=3,
    相位=12,
    旋转=0,
    使用角度制=True,
    模式='等比',
    方向='双向',
    颜色='#0f0',
    透明度=1,
    主半径=1,
    圆心=(0, 0),
    点数=1000,
    线型='-',
    线宽=1,
    ax=None,
    显示圆心=True,
    **kwargs,
):
    """波的波（波 of wave）——在波的位置上再次放置波。"""
    旋转弧度 = np.deg2rad(旋转) if 使用角度制 else 旋转
    for i in range(相位 + 1):
        波(
            振幅=振幅, 频率=频率, 相位=相位,
            旋转=旋转弧度, 使用角度制=False,
            模式=模式, 方向=方向, 颜色=颜色,
            透明度=透明度, 主半径=主半径,
            圆心=(
                圆心[0] + np.cos(i * 2 * np.pi / 相位 + np.pi / 2 + 旋转弧度),
                圆心[1] + np.sin(i * 2 * np.pi / 相位 + np.pi / 2 + 旋转弧度),
            ),
            点数=点数, 线型=线型, 线宽=线宽,
            ax=ax, 显示圆心=显示圆心,
            **kwargs,
        )


