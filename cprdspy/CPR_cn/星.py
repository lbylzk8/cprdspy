"""
星模块 — 星形图案的绘制

星形是花朵的特例（花瓣弧半径等于主半径），提供星形和多层星形的中文接口。
"""

import numpy as np
from .花 import 花, 多层花


def 星(
    主半径=1,
    r=1,
    n=4,
    N=12,
    旋转=0,
    使用角度制=True,
    颜色='#0F0',
    透明度=1,
    圆心=(0, 0),
    线型='-',
    线宽=1,
    边缘颜色='black',
    边缘透明度=1,
    ax=None,
    点数=4,
    **kwargs,
):
    """绘制星形图案（花瓣弧半径r=主半径R时形成星形）。

    参数:
        主半径 (float): 主圆半径R。
        r (float): 花瓣弧半径（与R相等时形成典型星形）。
        n (int): 星形基础数。
        N (int): 花瓣/星角数量。
        旋转 (float): 旋转角度。
        使用角度制 (bool): 旋转是否使用角度制。
    """
    花(
        主半径, r, n, N,
        旋转,
        颜色, 透明度, 圆心,
        点数, 线型, 线宽,
        使用角度制=使用角度制,
        **kwargs,
    )


def 多层星(
    主半径=1,
    r=1,
    n=4,
    公比=np.sqrt(2),
    M=3,
    N=12,
    颜色='#0F0',
    透明度=1,
    旋转=0,
    使用角度制=True,
    圆心=(0, 0),
    线型='-',
    线宽=1,
    边缘颜色='black',
    边缘透明度=1,
    ax=None,
    点数=4,
    **kwargs,
):
    """绘制多层星形图案。

    参数:
        主半径 (float): 最内层主圆半径R。
        r (float): 最内层花瓣弧半径。
        n (int): 星形基础数。
        公比 (float): 层间缩放比。
        M (int): 层数。
        N (int): 每层星角数量。
        旋转 (float): 旋转角度。
        使用角度制 (bool): 旋转是否使用角度制。
    """
    多层花(
        主半径, r, n, 公比, M, N,
        颜色, 透明度, 旋转,
        圆心, 点数, 线型, 线宽,
        使用角度制=使用角度制,
        **kwargs,
    )


__all__ = ["星", "多层星"]
